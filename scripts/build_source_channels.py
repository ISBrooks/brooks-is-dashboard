"""Build config/source_channels.csv (name -> channel) from an export of the
"IS Sourcing - INSIDE SALES SOURCING MASTER" Google Sheet.

    python scripts/build_source_channels.py "path/to/IS Sourcing - ... .csv"

Channel = the sheet's "Channel" column, normalised to one of
Paid / Organic / Affiliate Marketing / Generic (typos fixed, anything else ignored).
Every name on a row — Pestroutes Source, Current Source, Spend Sheet Key,
Genesys Data Table — maps to that channel. When the same name appears under
two channels the majority wins; a tie goes to the row that names a Current
Source (the live row). Hand corrections belong in
config/source_channel_overrides.csv, which wins over this generated file and
is never touched here."""
import csv
import sys
from collections import Counter, defaultdict
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / "config" / "source_channels.csv"
NORM = {"paid": "Paid", "organic": "Organic", "orgamic": "Organic",
        "affiliate marketing": "Affiliate Marketing", "affiliate": "Affiliate Marketing",
        "generic": "Generic"}
NAME_COLS = ("Pestroutes Source", "Current Source", "Spend Sheet Key", "Genesys Data Table")


def main(src: str) -> None:
    votes: dict[str, Counter] = defaultdict(Counter)
    shown: dict[str, str] = {}          # lower-case name -> name as written
    with open(src, encoding="utf-8-sig", newline="") as f:
        for row in csv.DictReader(f):
            ch = NORM.get((row.get("Channel") or "").strip().lower())
            if not ch:
                continue
            live = bool((row.get("Current Source") or "").strip())
            for col in NAME_COLS:
                name = (row.get(col) or "").strip()
                if not name or name == "-":
                    continue
                votes[name.lower()][ch] += 2 if live else 1
                shown.setdefault(name.lower(), name)
    OUT.parent.mkdir(exist_ok=True)
    with OUT.open("w", encoding="utf-8", newline="") as f:
        f.write("name,channel\n")
        f.write("# GENERATED by scripts/build_source_channels.py from the IS Sourcing master sheet —\n")
        f.write("# re-running overwrites this file. Put hand corrections in source_channel_overrides.csv.\n")
        w = csv.writer(f)
        for key in sorted(votes):
            w.writerow([shown[key], votes[key].most_common(1)[0][0]])
    print(f"wrote {OUT} ({len(votes)} names)")
    for key, c in sorted(votes.items()):
        if len(c) > 1:
            print(f"  note: '{shown[key]}' appears under {dict(c)} -> {c.most_common(1)[0][0]}")


if __name__ == "__main__":
    if len(sys.argv) != 2:
        sys.exit(__doc__)
    main(sys.argv[1])
